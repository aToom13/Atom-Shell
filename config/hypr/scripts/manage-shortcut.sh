#!/usr/bin/env bash
set -euo pipefail

config_home=${XDG_CONFIG_HOME:-$HOME/.config}
state_file="$config_home/caelestia/custom-shortcuts.json"
lua_file="$config_home/caelestia/custom-shortcuts.lua"
mkdir -p "$(dirname "$state_file")"

if [[ ! -f "$state_file" ]]; then
    printf '[]\n' > "$state_file"
fi

validate_field() {
    [[ "$1" != *$'\n'* && "$1" != *$'\t'* ]]
}

generate_lua() {
    local tmp
    tmp=$(mktemp "${lua_file}.XXXXXX")
    {
        printf '%s\n' '-- Generated by Nexus > Keyboard shortcuts. Do not edit manually.'
        jq -r '.[] | "hl.bind(" + (.key | tojson) + ", hl.dsp.exec_cmd(" + (.command | tojson) + "))"' "$state_file"
    } > "$tmp"
    mv "$tmp" "$lua_file"
}

case "${1:-list}" in
    list)
        jq -r '.[] | [.id, .key, .description, .command] | @tsv' "$state_file"
        ;;
    upsert)
        id=${2:-}
        key=${3:-}
        description=${4:-}
        command=${5:-}
        [[ -n "$key" && -n "$description" && -n "$command" ]]
        validate_field "$key" && validate_field "$description" && validate_field "$command"
        if [[ -z "$id" ]]; then
            id="custom-$(date +%s%N)"
        fi
        tmp=$(mktemp "${state_file}.XXXXXX")
        jq --arg id "$id" --arg key "$key" --arg description "$description" --arg command "$command" \
            'map(select(.id != $id)) + [{id: $id, key: $key, description: $description, command: $command}]' "$state_file" > "$tmp"
        mv "$tmp" "$state_file"
        generate_lua
        printf '%s\n' "$id"
        ;;
    delete)
        id=${2:-}
        [[ -n "$id" ]]
        tmp=$(mktemp "${state_file}.XXXXXX")
        jq --arg id "$id" 'map(select(.id != $id))' "$state_file" > "$tmp"
        mv "$tmp" "$state_file"
        generate_lua
        ;;
    *)
        printf 'usage: %s {list|upsert|delete}\n' "$0" >&2
        exit 2
        ;;
esac
